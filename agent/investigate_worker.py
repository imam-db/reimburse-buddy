"""Investigation worker: one LangGraph run on one claim, spoken over JSON lines on stdin/stdout.

The web admin (web/reimburse_web/agent_bridge.py) starts this as a subprocess inside the agent's
own uv environment, so the agent's dependencies never enter the root lockfile.

    uv --directory agent run python investigate_worker.py --claim CLM-2026-0110 [--fake-script f.json]

stdout events (one JSON object per line):
    {"type": "start", "model": ..., "compact": true}
    {"type": "step", "n": 1, "tool": ..., "args": {...}, "args_summary": ..., "result_summary": ...}
    {"type": "interrupt", "tool": ..., "args": {...}, "tool_call_id": ..., "approval_id": ...,
     "current_decision": {...check_claim summary...} | null}   -> waits for the matching answer
    {"type": "answer_applied", "approval_id": ..., "approved": bool}   the answer took effect
    {"type": "final", "note": ..., "tokens": {...}}
    {"type": "error", "code": "no_key" | "token_limit" | "exception", "message": ...}
    {"type": "answer_rejected", "approval_id": ..., "reason": "mismatch" | "malformed"}
    {"type": "auto_declined", "approval_id": ...}   approval deadline passed
stdin: {"approval_id": <id from the interrupt>, "approved": true|false, "reason": "..."}
       or {"cancel": true} at any time. approval_id is generated by the worker per interrupt.
       An answer whose approval_id is not the pending one
       (late duplicate, other tab, stale page) is rejected and never applied to another call.

Deadlines: --run-deadline seconds of agent work (default 600, error code "deadline"; the clock
pauses while an approval is pending),
--approval-deadline seconds per pending approval (default 900, then auto-decline).

Model: REIMBURSE_AGENT_MODEL (default deepseek-flash), REIMBURSE_AGENT_BASE_URL (default
https://api.deepseek.com), key from REIMBURSE_AGENT_API_KEY or DEEPSEEK_API_KEY. The key is
never printed. --fake-script replays scripted AIMessages (tests; no key, no network).
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import uuid

from langchain_core.messages import AIMessage
from langgraph.checkpoint.memory import InMemorySaver
from langgraph.types import Command

from reimburse_agent.config import build_chat_model, load_config
from reimburse_agent.graph import build_graph
from reimburse_agent.mcp_client import mcp_tools

DEFAULT_MODEL = "deepseek-flash"
DEFAULT_BASE_URL = "https://api.deepseek.com"


def emit(ev: dict) -> None:
    sys.stdout.write(json.dumps(ev, ensure_ascii=False, default=str) + "\n")
    sys.stdout.flush()


def summarize(x, limit: int = 160) -> str:
    s = x if isinstance(x, str) else json.dumps(x, ensure_ascii=False, default=str)
    s = " ".join(s.split())
    return s if len(s) <= limit else s[: limit - 1] + "…"


def api_key() -> str:
    return (os.environ.get("REIMBURSE_AGENT_API_KEY") or os.environ.get("DEEPSEEK_API_KEY") or "").strip()


def model_env() -> dict[str, str]:
    """Worker defaults on top of the env: DeepSeek flash, DEEPSEEK_API_KEY accepted as the key."""
    env = dict(os.environ)
    env.setdefault("REIMBURSE_AGENT_MODEL", DEFAULT_MODEL)
    env["REIMBURSE_AGENT_MODEL"] = env["REIMBURSE_AGENT_MODEL"] or DEFAULT_MODEL
    env["REIMBURSE_AGENT_BASE_URL"] = env.get("REIMBURSE_AGENT_BASE_URL") or DEFAULT_BASE_URL
    env["REIMBURSE_AGENT_API_KEY"] = api_key()
    return env


def make_model(fake_script: str | None):
    if fake_script:
        from langchain_core.language_models.fake_chat_models import GenericFakeChatModel

        class Scripted(GenericFakeChatModel):
            def bind_tools(self, tools, **kw):
                return self

        with open(fake_script, encoding="utf-8") as f:
            script = json.load(f)
        msgs = [AIMessage(content=m.get("content", ""), tool_calls=[
            {"name": c["name"], "args": c.get("args", {}), "id": c.get("id", f"call{i}-{j}")}
            for j, c in enumerate(m.get("tool_calls", []))]) for i, m in enumerate(script)]
        return Scripted(messages=iter(msgs)), "fake-scripted"
    cfg = load_config(model_env())
    return build_chat_model(cfg), cfg.model


class Cancelled(Exception):
    pass


class Stdin:
    """stdin lines as an asyncio queue (a reader thread), so waits can time out."""

    def __init__(self):
        import threading

        self.loop = asyncio.get_running_loop()
        self.q: asyncio.Queue = asyncio.Queue()
        self.held: list = []
        threading.Thread(target=self._pump, daemon=True).start()

    def _pump(self):
        for line in sys.stdin:
            self.loop.call_soon_threadsafe(self.q.put_nowait, line)
        self.loop.call_soon_threadsafe(self.q.put_nowait, None)

    def drain_cancel(self) -> None:
        """Between steps: honour a cancel at once; keep other lines for answer_for, which applies
        only the one matching the pending call and rejects the rest."""
        while not self.q.empty():
            line = self.q.get_nowait()
            if line is not None and parse(line).get("cancel"):
                raise Cancelled()
            self.held.append(line)

    async def _next(self, timeout: float):
        if self.held:
            return self.held.pop(0)
        return await asyncio.wait_for(self.q.get(), timeout)

    async def answer_for(self, call_id: str, timeout: float) -> dict | None:
        loop = asyncio.get_running_loop()
        end = loop.time() + timeout
        while True:
            left = end - loop.time()
            if left <= 0:
                return None
            try:
                line = await self._next(left)
            except asyncio.TimeoutError:
                return None
            if line is None:  # web side closed the pipe
                raise Cancelled()
            ans = parse(line)
            if ans.get("cancel"):
                raise Cancelled()
            if ans.get("approval_id") == call_id and isinstance(ans.get("approved"), bool):
                return ans
            emit({"type": "answer_rejected", "approval_id": ans.get("approval_id"),
                  "reason": "mismatch" if ans else "malformed"})


def parse(line: str | None) -> dict:
    try:
        v = json.loads(line) if line and line.strip() else {}
    except json.JSONDecodeError:
        return {}
    return v if isinstance(v, dict) else {}


def _find(exc: BaseException, kind) -> bool:
    """The MCP client's TaskGroup wraps our exceptions in ExceptionGroups."""
    if isinstance(exc, kind):
        return True
    return isinstance(exc, BaseExceptionGroup) and any(_find(e, kind) for e in exc.exceptions)


async def run(a) -> int:
    try:
        return await _run(a)
    except BaseException as exc:  # noqa: BLE001 - re-raised below unless it is ours
        if _find(exc, Cancelled):
            emit({"type": "error", "code": "cancelled", "message": "Cancelled by the reviewer."})
            return 5
        if not _find(exc, asyncio.TimeoutError):
            raise
        emit({"type": "error", "code": "deadline",
              "message": f"Stopped: run used more than {a.run_deadline}s (time waiting for approval not counted)."})
        return 4


async def current_decision(by_name: dict, args: dict) -> dict | None:
    """The rule engine's view of the claim, shown next to a proposed write (not the model's words)."""
    cid = args.get("claim_id") if isinstance(args, dict) else None
    if not cid or "check_claim" not in by_name:
        return None
    try:
        from reimburse_agent.compact import tool_text

        r = json.loads(tool_text(await by_name["check_claim"].ainvoke({"claim_id": cid})))
        return {k: r.get(k) for k in ("claim_id", "decision", "total_claimed", "total_approvable", "total_pending")}
    except Exception:
        return None


async def _run(a) -> int:
    if not a.fake_script and not api_key():
        emit({"type": "error", "code": "no_key",
              "message": "No model key configured. Set DEEPSEEK_API_KEY (or REIMBURSE_AGENT_API_KEY)."})
        return 2
    model, name = make_model(a.fake_script)
    emit({"type": "start", "model": name, "compact": True, "claim": a.claim})
    stdin = Stdin()
    tokens = {"input": 0, "output": 0}
    pending: dict[str, dict] = {}
    n = 0
    async with mcp_tools() as (_s, tools):
        graph = build_graph(model, tools, checkpointer=InMemorySaver(), compact=True)
        conf = {"configurable": {"thread_id": str(uuid.uuid4())}, "recursion_limit": a.max_steps}
        payload: object = {"messages": [("user", a.prompt.format(claim=a.claim))], "declined": {}}
        loop = asyncio.get_running_loop()
        budget = a.run_deadline  # seconds of agent work; the clock pauses while a human decides

        async def segment(payload) -> int | None:
            nonlocal n
            async for ev in graph.astream(payload, conf, stream_mode="updates"):
                stdin.drain_cancel()
                for node, upd in ev.items():
                    if node == "__interrupt__" or not isinstance(upd, dict):
                        continue
                    for m in upd.get("messages", []):
                        um = getattr(m, "usage_metadata", None) or {}
                        tokens["input"] += um.get("input_tokens", 0)
                        tokens["output"] += um.get("output_tokens", 0)
                        for c in getattr(m, "tool_calls", None) or []:
                            pending[c["id"]] = c
                        if m.type == "tool":
                            c = pending.pop(m.tool_call_id, {"name": m.name, "args": {}})
                            n += 1
                            emit({"type": "step", "n": n, "tool": c["name"], "args": c["args"],
                                  "args_summary": summarize(c["args"], 120),
                                  "result_summary": summarize(m.content),
                                  "declined": "reviewer_declined" in str(m.content)})
                    if tokens["input"] + tokens["output"] > a.max_tokens:
                        emit({"type": "error", "code": "token_limit", "tokens": tokens,
                              "message": f"Stopped: run used more than {a.max_tokens} tokens."})
                        return 3
            return None

        by_name = {t.name: t for t in tools}
        while True:
            t0 = loop.time()
            code = await asyncio.wait_for(segment(payload), max(budget, 0.001))
            budget -= loop.time() - t0
            if code is not None:
                return code
            state = await graph.aget_state(conf)
            if not state.interrupts:
                break
            req = state.interrupts[0].value
            approval_id = uuid.uuid4().hex  # ours, not the model's tool_call_id (may repeat across providers)
            emit({"type": "interrupt", **req, "approval_id": approval_id,
                  "current_decision": await current_decision(by_name, req.get("args", {}))})
            ans = await stdin.answer_for(approval_id, a.approval_deadline)
            if ans is None:
                emit({"type": "auto_declined", "approval_id": approval_id, "tool": req["tool"]})
                ans = {"approved": False, "reason": f"no answer within {a.approval_deadline}s; auto-declined"}
            else:
                emit({"type": "answer_applied", "approval_id": approval_id, "tool": req["tool"],
                      "approved": ans["approved"] is True, "reason": ans.get("reason", "")})
            approved = ans["approved"] is True
            payload = Command(resume={"approved": approved, "tool_call_id": req["tool_call_id"],
                                      "reason": "" if approved else (ans.get("reason") or "reviewer declined")})
        emit({"type": "final", "note": str(state.values["messages"][-1].content), "tokens": tokens})
    return 0


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--claim", required=True)
    p.add_argument("--prompt", default="Review claim {claim} and draft the decision note.")
    p.add_argument("--max-steps", type=int, default=60)
    p.add_argument("--max-tokens", type=int, default=int(os.environ.get("REIMBURSE_AGENT_MAX_TOKENS", "250000")))
    p.add_argument("--run-deadline", type=float, default=float(os.environ.get("REIMBURSE_AGENT_RUN_DEADLINE", "600")))
    p.add_argument("--approval-deadline", type=float,
                   default=float(os.environ.get("REIMBURSE_AGENT_APPROVAL_DEADLINE", "900")))
    p.add_argument("--fake-script")
    a = p.parse_args()
    try:
        code = asyncio.run(run(a))
    except Exception as exc:  # report, never a traceback with env in it
        emit({"type": "error", "code": "exception", "message": f"{type(exc).__name__}: {exc}"})
        code = 1
    sys.exit(code)


if __name__ == "__main__":
    main()
